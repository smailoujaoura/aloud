// Writes PIPER_VOICE_LICENCES.md: every Piper voice in public/models.json with the dataset it was
// trained on and that dataset's licence, as the voice's own model card states it.
//
// Aloud does not ship these voices — each is downloaded from Hugging Face when the reader asks for
// it — but the licences differ a great deal (public domain, attribution, share-alike,
// non-commercial, research-only), and models.json only says "see MODEL_CARD". The card is the
// authority; this file is a copy of what each card says, one network fetch per voice, cached
// under .gen/voice-cards/ so a rerun works offline.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const cacheDir = join(root, '.gen/voice-cards');

/** A licence statement, sorted into a kind a reader can act on. Non-commercial first: "by-nc-sa" is also share-alike. */
function kind(licence, url) {
  const s = `${licence} ${url}`.toLowerCase();
  if (/by-nc|\bnc\b|non-?commercial/.test(s)) return 'Non-commercial';
  if (/blizzard/.test(s)) return 'Research licence';
  if (/iitm|indictts/.test(licence.toLowerCase())) return 'IndicTTS licence';
  if (/cc0|public domain|unlicense/.test(s)) return 'Public domain';
  if (/by-sa|sharealike|by sa\b|cc-by-sa/.test(s)) return 'Share-alike';
  if (/agpl|\bgpl\b/.test(s)) return 'GPL';
  if (/apache/.test(s)) return 'Apache-2.0';
  if (/cc.?by|attribution|licenses\/by\//.test(s)) return 'Attribution';
  return 'Not stated on the card';
}

async function card(url, file) {
  if (existsSync(file)) return readFileSync(file, 'utf8');
  for (let attempt = 0; ; attempt++) {
    try {
      const res = await fetch(url, { signal: AbortSignal.timeout(30_000) });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const text = await res.text();
      writeFileSync(file, text);
      return text;
    } catch (err) {
      if (attempt >= 2) throw new Error(`${url}: ${err.message}`);
    }
  }
}

const cell = (s) => s.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

export async function writePiperLicences() {
  const manifest = JSON.parse(readFileSync(join(root, 'public/models.json'), 'utf8'));
  mkdirSync(cacheDir, { recursive: true });
  const ids = Object.keys(manifest.piper).sort();
  const rows = [];
  let next = 0;
  const worker = async () => {
    while (next < ids.length) {
      const id = ids[next++];
      const voice = manifest.piper[id];
      const url = voice.onnx.replace(/[^/]+\.onnx$/, 'MODEL_CARD');
      const text = await card(url, join(cacheDir, `${id}.md`));
      const dataset = text.split(/^## Dataset/im)[1] ?? '';
      const source = dataset.match(/URL:\s*(\S+)/i)?.[1] ?? '';
      const licence = dataset.match(/Licen[cs]e:\s*(.+)/i)?.[1]?.trim() ?? '';
      // A voice fine-tuned from another carries what that one was trained on too (Amy from Lessac).
      const base = text.match(/fine-?tuned from\s+(.+?)\.?\s*$/im)?.[1]?.replace(/[*`]/g, '').trim() ?? '';
      rows.push({ id, label: voice.label, url, source, licence, base, kind: kind(licence, source) });
    }
  };
  await Promise.all(Array.from({ length: 8 }, worker));
  rows.sort((a, b) => a.id.localeCompare(b.id));

  const counts = new Map();
  for (const r of rows) counts.set(r.kind, (counts.get(r.kind) ?? 0) + 1);
  const summary = [...counts].sort((a, b) => b[1] - a[1]).map(([k, n]) => `| ${k} | ${n} |`);

  const link = (s) => (/^(https?:\/\/|www\.)/.test(s) ? `<${s.startsWith('www.') ? `https://${s}` : s}>` : cell(s));
  const body = rows.map(
    (r) =>
      `| ${cell(r.label)} | \`${r.id}\` | ${r.kind} | ${r.licence ? link(r.licence) : '—'} | ${r.source ? link(r.source) : '—'} | ${r.base ? cell(r.base) : '—'} | [card](${r.url}) |`,
  );

  const md = `# Piper voices: what each was trained on, and under what licence

Generated by \`scripts/piper-licences.mjs\` from each voice's model card in
[rhasspy/piper-voices](https://huggingface.co/rhasspy/piper-voices), at the revision
\`public/models.json\` pins. Do not edit by hand.

Aloud does not include any voice: each one is downloaded from Hugging Face when you choose it.
The licence of a voice is the licence of the recordings it was trained on, and they differ — some
are public domain, some ask for attribution, some are for **non-commercial** use only, and the
Lessac voices (and voices fine-tuned from them) come from a research licence. The licence column
is copied from the model card word for word; where a card says only "See URL" or nothing, the
dataset's own page is the authority. A voice fine-tuned from another (most English ones, from
Lessac) was trained on that voice's recordings as well, so that licence applies to it too. The kind is a reading of that statement, to help you find
what matters; it is not legal advice.

| Kind | Voices |
|---|---|
${summary.join('\n')}

| Voice | Id | Kind | Licence, as the model card states it | Dataset | Fine-tuned from | Model card |
|---|---|---|---|---|---|---|
${body.join('\n')}
`;
  writeFileSync(join(root, 'PIPER_VOICE_LICENCES.md'), md);
  console.log(`[piper-licences] ${rows.length} voices → PIPER_VOICE_LICENCES.md`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await writePiperLicences();
